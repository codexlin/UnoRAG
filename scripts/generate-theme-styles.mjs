function oklchToLuminance(value) {
	const match = String(value).match(
		/^oklch\(\s*([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)\s*\)$/,
	);
	if (!match) return null;
	const L = Number(match[1]);
	const C = Number(match[2]);
	const H = (Number(match[3]) * Math.PI) / 180;
	const a = C * Math.cos(H);
	const b = C * Math.sin(H);
	const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
	const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
	const s_ = L - 0.0894841775 * a - 1.291485548 * b;
	const l = l_ ** 3;
	const m = m_ ** 3;
	const s = s_ ** 3;
	const r = Math.min(
		1,
		Math.max(0, 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
	);
	const g = Math.min(
		1,
		Math.max(0, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
	);
	const bl = Math.min(
		1,
		Math.max(0, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s),
	);
	return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
}

function contrastRatio(colorA, colorB) {
	const l1 = oklchToLuminance(colorA);
	const l2 = oklchToLuminance(colorB);
	if (l1 == null || l2 == null) return null;
	return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

function validateThemeValues(id, mode, values) {
	if (mode === "dark") {
		for (const token of [
			"card",
			"popover",
			"secondary",
			"muted",
			"accent",
			"border",
			"sidebar",
			"sidebar-accent",
			"sidebar-border",
		]) {
			const m = String(values[token] ?? "").match(/^oklch\(\s*([0-9.]+)/);
			if (m && Number(m[1]) > 0.55) {
				throw new Error(
					`Theme ${id}/${mode}/${token} has light-mode luminance (${values[token]}); add a dark override in overrides.json`,
				);
			}
		}
	}
	for (const [fg, bg] of [
		["foreground", "background"],
		["muted-foreground", "background"],
		["primary-foreground", "primary"],
		["secondary-foreground", "secondary"],
		["sidebar-foreground", "sidebar"],
		["sidebar-accent-foreground", "sidebar-accent"],
	]) {
		const ratio = contrastRatio(values[fg], values[bg]);
		if (ratio != null && ratio < 4.5) {
			throw new Error(
				`Theme ${id}/${mode} contrast too low: ${fg} on ${bg} = ${ratio.toFixed(2)}:1 (< 4.5:1)`,
			);
		}
	}
}

// Theme colors are upstream snapshots; product status colors and geometry stay independent.
export async function generateThemeStyles() {
	const overrides = JSON.parse(
		await readFile(new URL("src/styles/themes/overrides.json", root), "utf8"),
	);
	const rules = [
		"/* Generated by scripts/generate-theme-styles.mjs. Do not edit directly.",
		" * Adapted from tweakcn (Apache-2.0); upstream snapshots are in src/styles/themes/.",
		" * UnoRAG keeps status colors, spacing, tracking and radius independent of presets.",
		" */",
	];
	for (const [id, fonts] of Object.entries(presets)) {
		const theme = JSON.parse(
			await readFile(new URL(`src/styles/themes/${id}.json`, root), "utf8"),
		);
		if (theme.name !== id) throw new Error(`Unexpected theme: ${id}`);
		for (const mode of ["light", "dark"]) {
			const values = { ...theme.cssVars[mode], ...overrides[id]?.[mode] };
			values.evidence ??= values.primary;
			values["evidence-foreground"] ??= values["primary-foreground"];
			validateThemeValues(id, mode, values);
			const selector = `:root${mode === "dark" ? ".dark" : ""}[data-color-theme="${id}"]`;
			rules.push(
				"",
				`${id === "vercel" ? `${mode === "dark" ? ":root.dark" : ":root"},\n` : ""}${selector},\n${mode === "dark" ? ".dark " : ""}[data-theme-preview="${id}"] {`,
			);
			for (const key of [...colorTokens, ...shadows]) {
				if (typeof values[key] !== "string" || /[;{}]/.test(values[key]))
					throw new Error(`Invalid ${id}/${mode}/${key}`);
				rules.push(`\t--${key}: ${values[key]};`);
			}
			rules.push(
				`\t--theme-font-sans: ${fonts.sans};`,
				`\t--theme-font-mono: ${fonts.mono};`,
				"}",
			);
		}
	}
	return execFileSync(
		process.execPath,
		[
			require.resolve("@biomejs/biome/bin/biome"),
			"format",
			"--stdin-file-path=src/styles/themes.css",
		],
		{
			input: `${rules.join("\n")}\n`,
			encoding: "utf8",
		},
	);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const output = new URL("src/styles/themes.css", root);
	const css = await generateThemeStyles();
	const count = Object.keys(presets).length;
	if (process.argv.includes("--check")) {
		if ((await readFile(output, "utf8")) !== css)
			throw new Error("Theme CSS is stale; run pnpm themes:generate");
		console.log(`Verified ${count} built-in tweakcn themes (light/dark).`);
	} else {
		await writeFile(output, css);
		console.log(`Generated ${count} built-in tweakcn themes (light/dark).`);
	}
}
